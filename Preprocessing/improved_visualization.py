"""
Improved Visualization Script for Mesh Normalization Statistics

This script reads the CSV data generated by the normalization script and creates
enhanced, publication-quality plots with better formatting, larger text, and
improved visual clarity.

Features:
- Larger, clearer text and labels
- Better color schemes and styling
- Statistical annotations (mean, std, median)
- Improved histogram binning and outlier handling
- Professional formatting for reports/presentations
- Multiple plot styles (histograms, box plots, violin plots)
"""

